"""
Self-convergence functionlities of P2 fields for 2D standard FEM models containing a fracture. 

The models are solved with the standard T6 element without QPE, where the mid-side nodes are 
correctly placed at the midpoints of the edges in the original 2D grid.
"""
from __future__ import annotations

import numpy as np
import porepy as pp

import helpers.mdamr_local  # adds external/mdamr-main/src to sys.path
from mdamr.non_matching.transfer_grid import TransferGrid

from selfconv import QuadratureIntegration


def _rotate_fem_nodes_to_transfer_frame(
    nodes_xy: np.ndarray,
    rotation_matrix: np.ndarray,
    dim_bool: np.ndarray,
) -> np.ndarray:
    """Rotate FEM nodes into the same 2D frame using ``rotation_matrix`` 
    generated by ``TransferGrid``.

    Parameters: 
        nodes_xy: FEM node coordinates, shape = (num_nodes, 2).
        rotation_matrix: 3x3 rotation matrix used internally by ``TransferGrid``.
        dim_bool: active dimensions of the rotated grid.

    Returns: 
        Rotated 2D node coordinates, shape = (num_nodes, 2).

    Notes:
        The input nodes are in the original 2D grids, so ``rotation_matrix`` 
        is identity I. This method is involved only for consistency with the 
        non-matching grid transfer framework.
    """
    nodes3 = np.zeros((3, nodes_xy.shape[0]), dtype=float)
    nodes3[:2, :] = nodes_xy.T
    rot = rotation_matrix @ nodes3

    return rot[dim_bool, :].T


def _barycentric_coordinates(
    vertices: np.ndarray,
    points: np.ndarray,
) -> np.ndarray:
    """Compute barycentric coordinates of given points in a triangle.

    For any point p in the triangle, its barycentric coordinates (L0, L1, L2) satisfy
    p = L0·v0 + L1·v1 + L2·v2, and L0 + L1 + L2 = 1.

    Parameters:
        vertices: triangle vertices, shape = (2, 3), ordered as [v0, v1, v2].
        points: points, shape = (2, num_points).

    Returns:
        barycentric coordinates of given points, shape = (3, num_points), corresponding 
            to [v0, v1, v2].
    """
    A = np.vstack((vertices, np.ones(3)))
    rhs = np.vstack((points, np.ones(points.shape[1])))
    return np.linalg.solve(A, rhs)


def _t6_shape_functions_2d(L: np.ndarray) -> np.ndarray:
    """Compute T6 shape functions from barycentric coordinates of given points.

    The T6 node order in a triangle is consistent with the FEM mesh 
    construction: [v0, m01, v1, m12, v2, m02]. Correspondingly, the T6 shape 
    functions for these six nodes are defined as follows, where L0, L1, L2 are barycentric 
    coordinates of given points, respectively:
        N0 = L0 * (2.0*L0 - 1.0),
        N1 = 4.0 * L0 * L1,
        N2 = L1 * (2.0*L1 - 1.0),
        N3 = 4.0 * L1 * L2,
        N4 = L2 * (2.0*L2 - 1.0),
        N5 = 4.0 * L0 * L2.

    Parameters:
        L: shape = (3, num_points)
            barycentric coordinates, ordered as [L0, L1, L2] for vertices [v0, v1, v2].

    Returns:
        N: shape = (6, num_points)
            values of T6 shape functions at given points. 
    """
    L0 = L[0]
    L1 = L[1]
    L2 = L[2]

    return np.vstack(
        (
            L0 * (2.0 * L0 - 1.0),
            4.0 * L0 * L1,
            L1 * (2.0 * L1 - 1.0),
            4.0 * L1 * L2,
            L2 * (2.0 * L2 - 1.0),
            4.0 * L0 * L2,
        )
    )


def _fem_displacement_by_node(U: np.ndarray) -> np.ndarray:
    """Convert flattened FEM displacement (2*num_nodes,) 
    to shape = (2, num_nodes).
    """
    return np.vstack((U[0::2], U[1::2]))


def _eval_t6_2d(
    qx: np.ndarray,
    element_nodes: np.ndarray,
    element_u: np.ndarray,
) -> np.ndarray:
    """Compute a standard quadratic (P2) FEM displacement field at given points in 2D.

    This method assumes a standard T6 element, where the physical triangle is 
    represented by the corner vertices [v0, v1, v2] as indicated in ``element_nodes``. 
    This is ONLY valid for the standard T6 element without QPE, where the mid-side nodes 
    are correctly placed at the midpoints of the edges in the original 2D grid.

    Parameters: 
        qx: shape = (2, num_points),
            quadrature points in the same 2D frame as element_nodes.
        element_nodes: shape = (6, 2), 
            coordinates of the 6 T6 nodes, ordered as [v0, m01, v1, m12, v2, m02].
        element_u: shape = (2, 6),
            displacement values at the 6 T6 nodes. 

    Returns:
        displacement at given quadrature points, shape = (2, num_points).
    """
    vertices = element_nodes[[0, 2, 4], :].T
    # Compute barycentric coordinates of quadrature points in the triangle 
    # defined by the corner vertices.
    L = _barycentric_coordinates(vertices, qx)
    # Compute T6 shape functions at quadrature points.
    N = _t6_shape_functions_2d(L)
    return element_u @ N


def matrix_error_integration_t6_quad(
    coarse_model: object,
    fine_model: object,
    tol: float = 1e-8,
) -> tuple[float, float]:
    """Compute overlap-based relative L2 error components for T6 FEM fields on 2D grids
    using the quadrature rule.

    This implementation accesses the non-matching grid transfer methodology,  
    :class:`TransferGrid`, developed by Jhabriel Varela for mixed-dimensional geometry in
    PorePy. ``rotation_matrix`` are technically obtained from PorePy's original grids. 
    With this matrix, FEM nodes can be rotated as well with a additional method 
    :meth:`_rotate_fem_nodes_to_transfer_frame`.
    
    References: 
        - Varela, et al. (2025). arXiv preprint arXiv:2512.09087.

    It computes
        numerator_sq   = int_Omega |u_H^{T6} - u_h^{T6}|^2 dx
        denominator_sq = int_Omega |u_h^{T6}|^2 dx

    on the transfer grid generated by intersections of the coarse and fine
    PorePy matrix grids.

    Parameters: 
        coarse_model, fine_model: solved FEM models.
        tol: tolerance passed to ``TransferGrid``.

    Returns: 
        numerator_sq, denominator_sq: squared L2 numerator and denominator.
    """
    # Get grids: this grids are from PorePy originally. 
    sd_H = coarse_model.grid2d
    sd_h = fine_model.grid2d

    tg = TransferGrid(sd_H, sd_h, tol=tol, name="matrix_transfer_t6")
    src_rot = tg._get_rotated_grid(sd_H)
    tgt_rot = tg._get_rotated_grid(sd_h)

    # Rotation_matrix is created in ``TransferGrid``, while rotated nodes 
    # in FEM will be reconstructed based on this matrix. But since the input nodes 
    # are in the original 2D grids, the rotation_matrix is identity I.
    nodes_H = _rotate_fem_nodes_to_transfer_frame(
        coarse_model.nodes_p6,
        src_rot.rotation_matrix,
        src_rot.dim_bool,
    )
    nodes_h = _rotate_fem_nodes_to_transfer_frame(
        fine_model.nodes_p6,
        tgt_rot.rotation_matrix,
        tgt_rot.dim_bool,
    )

    elems_H = coarse_model.elements_t6
    elems_h = fine_model.elements_t6

    UH_node = _fem_displacement_by_node(coarse_model.U)
    Uh_node = _fem_displacement_by_node(fine_model.U)

    tr = tg.transfer
    tr_cells = QuadratureIntegration.transfer_triangles(tr)
    Xtr = tr.nodes[:2, :]

    t2s = tg.transfer_to_source.tocsr()
    t2t = tg.transfer_to_target.tocsr()

    numerator_sq = 0.0
    denominator_sq = 0.0
    for j, tr_nodes in enumerate(tr_cells):
        xy = Xtr[:, tr_nodes]

        qx, qw = QuadratureIntegration.triangle_quadrature_degree4(xy)

        # Get the parent coarse and fine cells corresponding to 
        # the current transfer cell.
        KH = t2s[j].indices[0]
        kh = t2t[j].indices[0]

        eH = elems_H[KH]
        eh = elems_h[kh]

        uH_q = _eval_t6_2d(
            qx=qx,
            element_nodes=nodes_H[eH],
            element_u=UH_node[:, eH],
        )
        uh_q = _eval_t6_2d(
            qx=qx,
            element_nodes=nodes_h[eh],
            element_u=Uh_node[:, eh],
        )

        diff_q = uH_q - uh_q
        numerator_sq += float(np.sum(qw * np.sum(diff_q**2, axis=0)))
        denominator_sq += float(np.sum(qw * np.sum(uh_q**2, axis=0)))

    return numerator_sq, denominator_sq


# For displacement jump on 1D fracture
def _p2_shape_functions_1d(xi: np.ndarray) -> np.ndarray:
    """Calculate values of quadratic (P2) shape functions at given points on 1D 
    reference coordinates, [-1, 1]. Three nodes on the 1D edge follows the 
    order: left, middle, right.

    Shape functions of these three nodes on 1D reference coordinates are defined 
    as follows:
        N0 = 0.5 * xi * (xi - 1.0),
        N1 = 1.0 - xi**2,
        N2 = 0.5 * xi * (xi + 1.0).

    Parameters:
        xi: shape = (num_points,)

    Returns:
        N: shape = (num_points, 3)
    """
    return np.vstack([
        0.5 * xi * (xi - 1.0),
        1.0 - xi**2,
        0.5 * xi * (xi + 1.0),
    ])


def _eval_p2_segment_1d(
    s_quad: np.ndarray,
    s_seg: np.ndarray,
    v_seg: np.ndarray,
) -> np.ndarray:
    """
    Calculate values of P2 field at given pointson one physical 1D segment.
    
    """
    s0 = s_seg[0]
    s2 = s_seg[2]

    # Map quadrature points from [s0, s2] to [-1, 1].
    xi = 2.0 * (s_quad - s0) / (s2 - s0) - 1.0
    N = _p2_shape_functions_1d(xi)

    return v_seg @ N


def _fracture_p2_jump_segments_from_model(model: object):
    theta = model.theta_rad
    t = np.array([np.sin(theta), np.cos(theta)])
    n = np.array([-np.cos(theta), np.sin(theta)])

    ux = model.U[0::2]
    uy = model.U[1::2]

    upper_edges = model.upper_frac_edge_dofs
    lower_edges = model.lower_frac_edge_dofs

    segs_n = []
    segs_t = []

    for upper, lower in zip(upper_edges, lower_edges):
        pts = model.nodes_p6[upper, :2]
        s = pts @ t

        idx = np.argsort(s)
        s = s[idx]
        upper = upper[idx]
        lower = lower[idx]

        u_upper = np.column_stack((ux[upper], uy[upper]))
        u_lower = np.column_stack((ux[lower], uy[lower]))

        jump = u_upper - u_lower

        segs_n.append((s, jump @ n))
        segs_t.append((s, jump @ t))

    segs_n.sort(key=lambda seg: seg[0][0])
    segs_t.sort(key=lambda seg: seg[0][0])

    return segs_n, segs_t


def _find_parent_segment(
    segments: list[tuple[np.ndarray, np.ndarray]],
    s_mid: float,
    tol: float = 1e-8,
) -> tuple[np.ndarray, np.ndarray]:
    """Find the P2 segment containing s_mid."""
    for s_seg, v_seg in segments:
        s_left = min(float(s_seg[0]), float(s_seg[2]))
        s_right = max(float(s_seg[0]), float(s_seg[2]))

        if s_left - tol <= s_mid <= s_right + tol:
            return s_seg, v_seg

    raise RuntimeError(f"No parent P2 segment found for s = {s_mid}.")


def fracture_error_integration_p2_quad(
    coarse_model: object,
    fine_model: object,
    tol: float = 1e-8,
    num_quad: int = 3,
) -> tuple[float, float, float, float]:

    segs_H_n, segs_H_t = _fracture_p2_jump_segments_from_model(coarse_model)
    segs_h_n, segs_h_t = _fracture_p2_jump_segments_from_model(fine_model)

    H_endpoints = np.array([seg[0][0] for seg in segs_H_n] + [segs_H_n[-1][0][2]])
    h_endpoints = np.array([seg[0][0] for seg in segs_h_n] + [segs_h_n[-1][0][2]])

    s_min = max(np.min(H_endpoints), np.min(h_endpoints))
    s_max = min(np.max(H_endpoints), np.max(h_endpoints))

    overlap_nodes = np.unique(
        np.round(
            np.concatenate([
                H_endpoints[(H_endpoints >= s_min - tol) & (H_endpoints <= s_max + tol)],
                h_endpoints[(h_endpoints >= s_min - tol) & (h_endpoints <= s_max + tol)],
            ]),
            decimals=14,
        )
    )

    xi, wi = np.polynomial.legendre.leggauss(num_quad)

    normal_num_sq = 0.0
    normal_den_sq = 0.0
    tangential_num_sq = 0.0
    tangential_den_sq = 0.0

    for s0, s1 in zip(overlap_nodes[:-1], overlap_nodes[1:]):
        s0 = float(s0)
        s1 = float(s1)

        if abs(s1 - s0) < tol:
            continue

        smid = 0.5 * (s0 + s1)

        s_seg_H_n, v_seg_H_n = _find_parent_segment(segs_H_n, smid, tol=tol)
        s_seg_h_n, v_seg_h_n = _find_parent_segment(segs_h_n, smid, tol=tol)

        s_seg_H_t, v_seg_H_t = _find_parent_segment(segs_H_t, smid, tol=tol)
        s_seg_h_t, v_seg_h_t = _find_parent_segment(segs_h_t, smid, tol=tol)

        mid = 0.5 * (s0 + s1)
        half = 0.5 * (s1 - s0)

        sq = mid + half * xi
        wq = abs(half) * wi

        jumpH_n_q = _eval_p2_segment_1d(sq, s_seg_H_n, v_seg_H_n)
        jumph_n_q = _eval_p2_segment_1d(sq, s_seg_h_n, v_seg_h_n)

        jumpH_t_q = _eval_p2_segment_1d(sq, s_seg_H_t, v_seg_H_t)
        jumph_t_q = _eval_p2_segment_1d(sq, s_seg_h_t, v_seg_h_t)

        diff_n_q = jumpH_n_q - jumph_n_q
        diff_t_q = jumpH_t_q - jumph_t_q

        normal_num_sq += float(np.sum(wq * diff_n_q**2))
        normal_den_sq += float(np.sum(wq * jumph_n_q**2))

        tangential_num_sq += float(np.sum(wq * diff_t_q**2))
        tangential_den_sq += float(np.sum(wq * jumph_t_q**2))

    return (
        normal_num_sq,
        normal_den_sq,
        tangential_num_sq,
        tangential_den_sq,
    )


def relative_error_p2_fem(
    coarse_model: object,
    fine_model: object,
    tol: float = 1e-8,
) -> tuple[float, float]:
    """Return matrix relative L2 error and its squared components.
    """

    matrix_num_sq, matrix_den_sq = matrix_error_integration_t6_quad(
        coarse_model=coarse_model,
        fine_model=fine_model,
        tol=tol,
    )

    (
        normal_num_sq,
        normal_den_sq,
        tangential_num_sq,
        tangential_den_sq,
    ) = fracture_error_integration_p2_quad(
        coarse_model=coarse_model,
        fine_model=fine_model,
        tol=tol,
        num_quad=3,
    )

    matrix_error = np.sqrt(matrix_num_sq / matrix_den_sq)
    fracture_error = np.sqrt(
        (normal_num_sq + tangential_num_sq) 
        / (normal_den_sq + tangential_den_sq)
    )  
  
    return matrix_error, fracture_error

