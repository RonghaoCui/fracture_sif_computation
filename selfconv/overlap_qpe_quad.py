        #     )
        # else:
        #     uH_q = _eval_t6_2d(
        #         qx=qx,
        #         element_nodes=nodes_H[eH],
        #         element_u=UH_node[:, eH],
        #     )

        # if kh in qpe_h:
        #     uh_q = _eval_qpe_collapsed_q8_2d(
        #         qx=qx,
        #         element_nodes=nodes_h[eh],
        #         element_u=Uh_node[:, eh],
