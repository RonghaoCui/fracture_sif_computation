def _rotate_fem_nodes_to_transfer_frame(
    nodes_xy: np.ndarray,
    rotation_matrix: np.ndarray,
    dim_bool: np.ndarray,
) -> np.ndarray:
    """Rotate FEM nodes into the same 2D frame using ``rotation_matrix`` 
    generated by ``TransferGrid``.

    Parameters: 
        nodes_xy: FEM node coordinates, shape = (num_nodes, 2).
        rotation_matrix: 3x3 rotation matrix used internally by ``TransferGrid``.
        dim_bool: active dimensions of the rotated grid.

    Returns: 
        Rotated 2D node coordinates, shape = (num_nodes, 2).

    Notes:
        The input nodes are in the original 2D grids, so ``rotation_matrix`` 
        is identity I. This method is involved only for consistency with the 
        non-matching grid transfer framework.
    """
    nodes3 = np.zeros((3, nodes_xy.shape[0]), dtype=float)
    nodes3[:2, :] = nodes_xy.T
    rot = rotation_matrix @ nodes3

    return rot[dim_bool, :].T


def _barycentric_coordinates(
    vertices: np.ndarray,
    points: np.ndarray,
) -> np.ndarray:
    """Compute barycentric coordinates of given points in a triangle.

    For any point p in the triangle, its barycentric coordinates (L0, L1, L2) satisfy
    p = L0·v0 + L1·v1 + L2·v2, and L0 + L1 + L2 = 1.

    Parameters:
        vertices: triangle vertices, shape = (2, 3), ordered as [v0, v1, v2].
        points: points, shape = (2, num_points).

    Returns:
        barycentric coordinates of given points, shape = (3, num_points), corresponding 
            to [v0, v1, v2].
    """
    A = np.vstack((vertices, np.ones(3)))
    rhs = np.vstack((points, np.ones(points.shape[1])))
    return np.linalg.solve(A, rhs)


def _t6_shape_functions_2d(L: np.ndarray) -> np.ndarray:
    """Compute T6 shape functions from barycentric coordinates of given points.

    The T6 node order in a triangle is consistent with the FEM mesh 
    construction: [v0, m01, v1, m12, v2, m02]. Correspondingly, the T6 shape 
    functions for these six nodes are defined as follows, where L0, L1, L2 are barycentric 
    coordinates of given points, respectively:
        N0 = L0 * (2.0*L0 - 1.0),
        N1 = 4.0 * L0 * L1,
        N2 = L1 * (2.0*L1 - 1.0),
        N3 = 4.0 * L1 * L2,
        N4 = L2 * (2.0*L2 - 1.0),
        N5 = 4.0 * L0 * L2.

    Parameters:
        L: shape = (3, num_points)
            barycentric coordinates, ordered as [L0, L1, L2] for vertices [v0, v1, v2].

    Returns:
        N: shape = (6, num_points)
            values of T6 shape functions at given points. 
    """
    L0 = L[0]
    L1 = L[1]
    L2 = L[2]

    return np.vstack(
        (
            L0 * (2.0 * L0 - 1.0),
            4.0 * L0 * L1,
            L1 * (2.0 * L1 - 1.0),
            4.0 * L1 * L2,
            L2 * (2.0 * L2 - 1.0),
            4.0 * L0 * L2,
        )
    )


def _fem_displacement_by_node(U: np.ndarray) -> np.ndarray:
    """Convert flattened FEM displacement (2*num_nodes,) 
    to shape = (2, num_nodes).
    """
    return np.vstack((U[0::2], U[1::2]))


def _eval_t6_2d(
    qx: np.ndarray,
    element_nodes: np.ndarray,
    element_u: np.ndarray,
) -> np.ndarray:
    """Compute a standard quadratic (P2) FEM displacement field at given points in 2D.

    This method assumes a standard T6 element, where the physical triangle is 
    represented by the corner vertices [v0, v1, v2] as indicated in ``element_nodes``. 
    This is ONLY valid for the standard T6 element without QPE, where the mid-side nodes 
    are correctly placed at the midpoints of the edges in the original 2D grid.

    Parameters: 
        qx: shape = (2, num_points),
            quadrature points in the same 2D frame as element_nodes.
        element_nodes: shape = (6, 2), 
            coordinates of the 6 T6 nodes, ordered as [v0, m01, v1, m12, v2, m02].
        element_u: shape = (2, 6),
            displacement values at the 6 T6 nodes. 

    Returns:
        displacement at given quadrature points, shape = (2, num_points).
    """
    vertices = element_nodes[[0, 2, 4], :].T
    # Compute barycentric coordinates of quadrature points in the triangle 
    # defined by the corner vertices.
    L = _barycentric_coordinates(vertices, qx)
    # Compute T6 shape functions at quadrature points.
    N = _t6_shape_functions_2d(L)
    return element_u @ N

def _q8_shape_functions_and_derivatives(
    xi: float,
    eta: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Q8 serendipity shape functions and derivatives.

    Node order follows your mmfa.Q8element:
        0: (-1,-1), 1: (0,-1), 2: (1,-1), 3: (1,0),
        4: (1,1),   5: (0,1),  6: (-1,1), 7: (-1,0)
    """
    corx = np.array([-1, 0, 1, 1, 1, 0, -1, -1], dtype=float)
    cory = np.array([-1, -1, -1, 0, 1, 1, 1, 0], dtype=float)

    N = np.zeros(8)
    dN_dxi = np.zeros(8)
    dN_deta = np.zeros(8)

    for i in range(8):
        xisi = corx[i]
        etai = cory[i]

        N[i] = (
            ((1.0 + xi * xisi) * (1.0 + eta * etai)
             - (1.0 - xi**2) * (1.0 + eta * etai)
             - (1.0 - eta**2) * (1.0 + xi * xisi))
            * xisi**2 * etai**2 / 4.0
            + (1.0 - xi**2) * (1.0 + eta * etai)
            * (1.0 - xisi**2) * etai**2 / 2.0
            + (1.0 - eta**2) * (1.0 + xi * xisi)
            * (1.0 - etai**2) * xisi**2 / 2.0
        )

        dN_dxi[i] = (
            (xisi * (1.0 + eta * etai)
             + 2.0 * xi * (1.0 + eta * etai)
             - xisi * (1.0 - eta**2))
            * xisi**2 * etai**2 / 4.0
            - 2.0 * xi * (1.0 + eta * etai)
            * (1.0 - xisi**2) * etai**2 / 2.0
            + xisi * (1.0 - eta**2)
            * (1.0 - etai**2) * xisi**2 / 2.0
        )

        dN_deta[i] = (
            (etai * (1.0 + xi * xisi)
             - etai * (1.0 - xi**2)
             + 2.0 * eta * (1.0 + xi * xisi))
            * xisi**2 * etai**2 / 4.0
            + etai * (1.0 - xi**2)
            * (1.0 - xisi**2) * etai**2 / 2.0
            - 2.0 * eta * (1.0 + xi * xisi)
            * (1.0 - etai**2) * xisi**2 / 2.0
        )

    return N, dN_dxi, dN_deta


def _collapsed_q8_shape_functions_and_derivatives(
    xi: float,
    eta: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Collapse Q8 shape functions to the six-node QPE representation.

    This matches your stiffness assembly:
        M0 = N0 + N6 + N7
        M1 = N1
        M2 = N2
        M3 = N3
        M4 = N4
        M5 = N5
    """
    N8, dN8_dxi, dN8_deta = _q8_shape_functions_and_derivatives(xi, eta)

    M = np.array([
        N8[0] + N8[6] + N8[7],
        N8[1],
        N8[2],
        N8[3],
        N8[4],
        N8[5],
    ])

    dM_dxi = np.array([
        dN8_dxi[0] + dN8_dxi[6] + dN8_dxi[7],
        dN8_dxi[1],
        dN8_dxi[2],
        dN8_dxi[3],
        dN8_dxi[4],
        dN8_dxi[5],
    ])

    dM_deta = np.array([
        dN8_deta[0] + dN8_deta[6] + dN8_deta[7],
        dN8_deta[1],
        dN8_deta[2],
        dN8_deta[3],
        dN8_deta[4],
        dN8_deta[5],
    ])

    return M, dM_dxi, dM_deta


def _inverse_collapsed_q8_coordinates(
    x_phys: np.ndarray,
    element_nodes: np.ndarray,
    tol: float = 1e-12,
    max_iter: int = 500,
) -> tuple[float, float]:
    """Find Q8 reference coordinates (xi, eta) for one physical point.

    This is the inverse of the collapsed-Q8 geometry mapping used by QPE.
    """
    # Use standard T6 barycentric coordinates as an initial guess.
    vertices = element_nodes[[0, 2, 4], :].T
    L0, L1, L2 = _barycentric_coordinates(
        vertices,
        x_phys.reshape(2, 1),
    ).ravel()

    # Map triangle barycentric guess to a rough Q8-square guess.
    # This is not exact, but usually good enough for Newton.
    xi = 2.0 * L1 + L2 - 1.0
    eta = L2 - L0

    for _ in range(max_iter):
        M, dM_dxi, dM_deta = _collapsed_q8_shape_functions_and_derivatives(
            xi,
            eta,
        )

        x_map = element_nodes.T @ M
        residual = x_map - x_phys

        if np.linalg.norm(residual) < tol:
            print(f"Converged in {_} iterations with residual norm {np.linalg.norm(residual):.2e}")
            return xi, eta

        dx_dxi = element_nodes.T @ dM_dxi
        dx_deta = element_nodes.T @ dM_deta

        J = np.column_stack((dx_dxi, dx_deta))

        delta = np.linalg.solve(J, residual)

        xi -= float(delta[0])
        eta -= float(delta[1])

    raise RuntimeError(
        "Newton failed in inverse collapsed-Q8 mapping."
    )


def _eval_qpe_collapsed_q8_2d(
    qx: np.ndarray,
    element_nodes: np.ndarray,
    element_u: np.ndarray,
) -> np.ndarray:
    """Evaluate QPE displacement using the same collapsed-Q8 basis as assembly.

    Parameters
    ----------
    qx:
        Physical quadrature points, shape = (2, num_points).
    element_nodes:
        Six QPE/T6 node coordinates, shape = (6, 2).
    element_u:
        Six nodal displacement values, shape = (2, 6).

    Returns
    -------
    uq:
        Displacement at quadrature points, shape = (2, num_points).
    """
    uq = np.zeros((2, qx.shape[1]), dtype=float)

    for k in range(qx.shape[1]):
        xi, eta = _inverse_collapsed_q8_coordinates(
            x_phys=qx[:, k],
            element_nodes=element_nodes,
        )

        M, _, _ = _collapsed_q8_shape_functions_and_derivatives(xi, eta)
        uq[:, k] = element_u @ M

    return uq


def _qpe_cell_set(model: object) -> set[int]:
    """Return cell indices marked as QPE."""
    qpe_cells: list[int] = []

    for cells in model.elements_quarter:
        if len(cells) > 0:
            qpe_cells.extend(np.asarray(cells, dtype=int).tolist())

    return set(np.unique(qpe_cells).tolist())


def _t6_shape_function_derivatives_from_xi_eta(
    xi: float,
    eta: float,
) -> tuple[np.ndarray, np.ndarray]:
    """Derivatives of T6 shape functions wrt xi and eta.

    Reference coordinates:
        L0 = 1 - xi - eta
        L1 = xi
        L2 = eta

    Node order:
        [v0, m01, v1, m12, v2, m02]
    """
    L0 = 1.0 - xi - eta
    L1 = xi
    L2 = eta

    dN_dxi = np.array([
        1.0 - 4.0 * L0,          # d/dxi of L0(2L0-1)
        4.0 * (L0 - L1),         # d/dxi of 4L0L1
        4.0 * L1 - 1.0,          # d/dxi of L1(2L1-1)
        4.0 * L2,                # d/dxi of 4L1L2
        0.0,                     # d/dxi of L2(2L2-1)
        -4.0 * L2,               # d/dxi of 4L0L2
    ])

    dN_deta = np.array([
        1.0 - 4.0 * L0,          # d/deta of L0(2L0-1)
        -4.0 * L1,               # d/deta of 4L0L1
        0.0,                     # d/deta of L1(2L1-1)
        4.0 * L1,                # d/deta of 4L1L2
        4.0 * L2 - 1.0,          # d/deta of L2(2L2-1)
        4.0 * (L0 - L2),         # d/deta of 4L0L2
    ])

    return dN_dxi, dN_deta


def _inverse_t6_isoparametric_coordinates(
    x_phys: np.ndarray,
    element_nodes: np.ndarray,
    tol: float = 1e-12,
    max_iter: int = 500,
) -> tuple[float, float]:
    """Find reference coordinates (xi, eta) for one physical point.

    This is needed for QPE elements, where the mid-side nodes are shifted and
    the physical-to-reference map is no longer the linear barycentric map.
    """
    vertices = element_nodes[[0, 2, 4], :].T

    # Linear barycentric coordinates are a good initial guess.
    L_init = _barycentric_coordinates(vertices, x_phys.reshape(2, 1)).ravel()
    xi = float(L_init[1])
    eta = float(L_init[2])

    for _ in range(max_iter):
        L = np.array([[1.0 - xi - eta], [xi], [eta]])
        N = _t6_shape_functions_2d(L).ravel()

        x_map = element_nodes.T @ N
        residual = x_map - x_phys

        if np.linalg.norm(residual) < tol:
            return xi, eta

        dN_dxi, dN_deta = _t6_shape_function_derivatives_from_xi_eta(xi, eta)

        dx_dxi = element_nodes.T @ dN_dxi
        dx_deta = element_nodes.T @ dN_deta

        J = np.column_stack((dx_dxi, dx_deta))

        delta = np.linalg.solve(J, residual)

        xi -= float(delta[0])
        eta -= float(delta[1])

    raise RuntimeError(
        "Newton iteration failed in inverse T6 isoparametric mapping."
    )


def _eval_t6_isoparametric_2d(
    qx: np.ndarray,
    element_nodes: np.ndarray,
    element_u: np.ndarray,
) -> np.ndarray:
    """Evaluate a T6/QPE displacement field at physical points.

    This works for both standard T6 and QPE elements. For QPE, it performs
    an inverse isoparametric mapping from physical coordinates to reference
    coordinates before evaluating the T6 shape functions.
    """
    uq = np.zeros((2, qx.shape[1]), dtype=float)

    for k in range(qx.shape[1]):
        xi, eta = _inverse_t6_isoparametric_coordinates(
            x_phys=qx[:, k],
            element_nodes=element_nodes,
        )

        L = np.array([[1.0 - xi - eta], [xi], [eta]])
        N = _t6_shape_functions_2d(L)

        uq[:, k] = (element_u @ N).ravel()

    return uq

def matrix_error_integration_t6_quad(
    coarse_model: object,
    fine_model: object,
    use_qpe: bool,
    tol: float = 1e-8,
) -> tuple[float, float]:
    """Compute overlap-based relative L2 error components for T6 FEM fields on 2D grids
    using the quadrature rule.

    This implementation accesses the non-matching grid transfer methodology,  
    :class:`TransferGrid`, developed by Jhabriel Varela for mixed-dimensional geometry in
    PorePy. ``rotation_matrix`` are technically obtained from PorePy's original grids. 
    With this matrix, FEM nodes can be rotated as well with a additional method 
    :meth:`_rotate_fem_nodes_to_transfer_frame`.
    
    References: 
        - Varela, et al. (2025). arXiv preprint arXiv:2512.09087.

    It computes
        numerator_sq   = int_Omega |u_H^{T6} - u_h^{T6}|^2 dx
        denominator_sq = int_Omega |u_h^{T6}|^2 dx

    on the transfer grid generated by intersections of the coarse and fine
    PorePy matrix grids.

    Parameters: 
        coarse_model, fine_model: solved FEM models.
        tol: tolerance passed to ``TransferGrid``.

    Returns: 
        numerator_sq, denominator_sq: squared L2 numerator and denominator.
    """
    # Get grids: this grids are from PorePy originally. 
    sd_H = coarse_model.grid2d
    sd_h = fine_model.grid2d

    tg = TransferGrid(sd_H, sd_h, tol=tol, name="matrix_transfer_t6")
    src_rot = tg._get_rotated_grid(sd_H)
    tgt_rot = tg._get_rotated_grid(sd_h)

    # Rotation_matrix is created in ``TransferGrid``, while rotated nodes 
    # in FEM will be reconstructed based on this matrix. But since the input nodes 
    # are in the original 2D grids, the rotation_matrix is identity I.
    nodes_H = _rotate_fem_nodes_to_transfer_frame(
        coarse_model.nodes_p6,
        src_rot.rotation_matrix,
        src_rot.dim_bool,
    )
    nodes_h = _rotate_fem_nodes_to_transfer_frame(
        fine_model.nodes_p6,
        tgt_rot.rotation_matrix,
        tgt_rot.dim_bool,
    )

    elems_H = coarse_model.elements_t6
    elems_h = fine_model.elements_t6

    UH_node = _fem_displacement_by_node(coarse_model.U)
    Uh_node = _fem_displacement_by_node(fine_model.U)

    tr = tg.transfer
    tr_cells = QuadratureIntegration.transfer_triangles(tr)
    Xtr = tr.nodes[:2, :]

    t2s = tg.transfer_to_source.tocsr()
    t2t = tg.transfer_to_target.tocsr()

    qpe_H = _qpe_cell_set(coarse_model) if use_qpe else set()
    qpe_h = _qpe_cell_set(fine_model) if use_qpe else set()

    numerator_sq = 0.0
