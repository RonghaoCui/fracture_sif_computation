"""
Self-convergence functionlities of P1 fields for 2D MPSA models containing a fracture. 

"""
from __future__ import annotations

import numpy as np
import porepy as pp

from mdamr.non_matching.transfer_grid import TransferGrid, TransferLine

from selfconv import QuadratureIntegration


def _cell_nodes(sd: pp.Grid) -> np.ndarray:
    """Get node indices for each cell. 
    
    Only simplex grids are supported: 
        - 2D triangles  -> 3 nodes: [node_i, node_j, node_k].
        - 1D segments   -> 2 nodes: [node_i, node_j]. 

    Parameters:
        sd: grid        

    Returns:
        node indices: shape = (num_cells, dim + 1)
    """
    cn = sd.cell_nodes().tocsc()
    return cn.indices.reshape((sd.dim + 1, sd.num_cells), order="F").T 


def _nodal_average_from_cell_values(
    sd: pp.Grid,
    values_cc: np.ndarray,
    weight: str = "volume",
) -> np.ndarray:
    """Reconstruction of nodal values from cell-center values. 

    The weight can be either "volume" or "uniform". 
    The former gives a volume-weighted average, while the latter gives a simple average.

    Cell-center variables should be vector. 
    Particularly, displacement variables are vector.

    Returns: 
        values_cc: shape (n_components, num_cells) for vector.
    """
    n_comp = values_cc.shape[0]
    u_node = np.zeros((n_comp, sd.num_nodes))
    w_node = np.zeros(sd.num_nodes)

    cells = _cell_nodes(sd)

    for c, nodes in enumerate(cells):
        if weight == "volume":
            w = float(sd.cell_volumes[c])
        elif weight == "uniform":
            w = 1.0
        else:
            raise ValueError("weight must be 'volume' or 'uniform'.")

        u_node[:, nodes] += w * values_cc[:, c, None]
        w_node[nodes] += w

    u_node /= w_node[None, :]

    return u_node


def _p1_coefficients_from_nodal_values_2d(
    sd: pp.Grid,
    nodal_values: np.ndarray,
    node_xy: np.ndarray,
) -> np.ndarray:
    """Compute cell-wise coefficients as a P1 continuous field in 2D.

    Parameters: 
        sd: 2D grid. 
        nodal_values: vector, shape = (n_components, num_nodes).
        node_xy: shape = (2, num_nodes), in the same coordinate used 
            by :class:`TransferGrid`.

    Returns: 
        coeff: shape = (n_components, num_cells, 3).
            For each component and cell, 3 coefficients [a, b, c] define the field. 
            coeff[comp, cell] = [a, b, c] represents u(x,y) = a*x + b*y + c.
    """
    n_comp = nodal_values.shape[0]
    cells = _cell_nodes(sd)

    coeff = np.zeros((n_comp, sd.num_cells, 3))

    for i, nodes in enumerate(cells):
        xy = node_xy[:, nodes] 
        # Construct the matrix for the three vertices of the triangle. 
        # A = [[x0, y0, 1],  -> node 0
        #      [x1, y1, 1],  -> node 1
        #      [x2, y2, 1]]. -> node 2
        A = np.column_stack((xy[0], xy[1], np.ones(3)))  

        for j in range(n_comp):
            rhs = nodal_values[j, nodes]
            coeff[j, i, :] = np.linalg.solve(A, rhs)

    return coeff


def _eval_p1_2d(coeff: np.ndarray, xy: np.ndarray) -> np.ndarray:
    """
    Compute the P1 field at given points in 2D.

    Parameters:
        coeff: shape = (n_components, 3)
        xy: shape = (2, n_points)

    Returns: 
        shape = (n_components, n_points)
    """
    return coeff[:, 0:1] * xy[0][None, :] + coeff[:, 1:2] * xy[1][None, :] + coeff[:, 2:3]


def matrix_error_integration_p1_quad(
    sd_H: pp.Grid,
    sd_h: pp.Grid,
    uH_cc: np.ndarray,
    uh_cc: np.ndarray,
    weight: str = "volume",
    tol: float = 1e-8,
) -> tuple[float, float]:
    """Compute overlap-based relative L2 error components for P1 fields on 2D grids
    using the quadrature rule.

    This implementation accesses the non-matching grid transfer methodology,  
    :class:`TransferGrid`, developed by Jhabriel Varela. PorePy grids are typically 
    stored as embeded 3D coordinates, even for 2D grids. :class:`TransferGrid` internally 
    maps coarse and fine grids to a shared rotated 2D coordinate frame, where the transfer 
    grid is generated by intersecting the coarse and fine cells.
    
    Reference: 
        - Varela, et al. (2025). arXiv preprint arXiv:2512.09087.

    It computes: 
        numerator_sq   = ∫_Omega |u_H^P1 - u_h^P1|^2 dx
        denominator_sq = ∫_Omega |u_h^P1|^2 dx
    
    on the transfer grid generated by intersections of coarse and fine cells.

    """
    tg = TransferGrid(sd_H, sd_h, tol=tol, name="matrix_transfer")

    # Get the rotated grids for coarse and fine meshes.
    src_rot = tg._get_rotated_grid(sd_H)
    tgt_rot = tg._get_rotated_grid(sd_h)

    # Reconstruct nodal values from cell-center values on the original grids.
    uH_node = _nodal_average_from_cell_values(sd_H, uH_cc, weight=weight)
    uh_node = _nodal_average_from_cell_values(sd_h, uh_cc, weight=weight)

    # Compute P1 coefficients for coarse and fine grids in the common rotated coordinates.
    # Rotated nodes are used. 
    CH = _p1_coefficients_from_nodal_values_2d(
        sd_H, uH_node, src_rot.nodes[:2, :]
    )
    Ch = _p1_coefficients_from_nodal_values_2d(
        sd_h, uh_node, tgt_rot.nodes[:2, :]
    )

    tr = tg.transfer   # the transfer grid
    tr_cells = QuadratureIntegration.transfer_triangles(tr)
    Xtr = tr.nodes[:2, :]

    # Get the mapping from transfer cells to source (coarse) and 
    # target (fine) grids.
    t2s = tg.transfer_to_source.tocsr()
    t2t = tg.transfer_to_target.tocsr()

    numerator_sq = 0.0
    denominator_sq = 0.0
    num_quad = 7
    for j, nodes in enumerate(tr_cells):
        xy = Xtr[:, nodes]
        
        # quad_x, quad_w = QuadratureIntegration.triangle_quadrature_degree4(xy)
        quad_x, quad_w = QuadratureIntegration.triangle_quadrature_gaussian(xy, num_quad)

        # Get the parent coarse and fine cells corresponding to 
        # the current transfer cell.
        KH = t2s[j].indices[0]
        kh = t2t[j].indices[0]

        uH_q = _eval_p1_2d(CH[:, KH, :], quad_x)
        uh_q = _eval_p1_2d(Ch[:, kh, :], quad_x)

        diff_q = uH_q - uh_q

        numerator_sq += float(np.sum(quad_w * np.sum(diff_q**2, axis=0)))
        denominator_sq += float(np.sum(quad_w * np.sum(uh_q**2, axis=0)))

    return numerator_sq, denominator_sq


def matrix_error_integration_p1_exact(
    sd_H: pp.Grid,
    sd_h: pp.Grid,
    uH_cc: np.ndarray,
    uh_cc: np.ndarray,
    weight: str = "volume",
    tol: float = 1e-8,
) -> tuple[float, float]:
    """
    Compute overlap-based relative L2 error components for P1 fields on 2D grids
    using exact integration.

    Notes:
        This is a reference implementation for testing the quadrature-based method. 
        The exact integration is performed by the exact 1D P1 mass matrix on each 
        triangle. This cannot be used for P2 fields. 
    """
    tg = TransferGrid(sd_H, sd_h, tol=tol, name="matrix_transfer")

    src_rot = tg._get_rotated_grid(sd_H)
    tgt_rot = tg._get_rotated_grid(sd_h)

    uH_node = _nodal_average_from_cell_values(sd_H, uH_cc, weight=weight)
    uh_node = _nodal_average_from_cell_values(sd_h, uh_cc, weight=weight)

    CH = _p1_coefficients_from_nodal_values_2d(
        sd_H, uH_node, src_rot.nodes[:2, :]
    )
    Ch = _p1_coefficients_from_nodal_values_2d(
        sd_h, uh_node, tgt_rot.nodes[:2, :]
    )

    tr = tg.transfer
    tr_cells = QuadratureIntegration.transfer_triangles(tr)
    Xtr = tr.nodes[:2, :]

    # Exact P1 mass matrix on a triangle:
    # ∫_T phi_i phi_j dx = |T|/12 * [[2,1,1],[1,2,1],[1,1,2]]
    M_ref = np.array(
        [[2.0, 1.0, 1.0],
         [1.0, 2.0, 1.0],
         [1.0, 1.0, 2.0]]
    ) / 12.0

    numerator_sq = 0.0
    denominator_sq = 0.0

    t2s = tg.transfer_to_source.tocsr()
    t2t = tg.transfer_to_target.tocsr()

    for j, nodes in enumerate(tr_cells):
        xy = Xtr[:, nodes]
        area = QuadratureIntegration.triangle_area(xy)

        # Get the parent coarse and fine cells corresponding to 
        # the current transfer cell.
        KH = t2s[j].indices[0]
        kh = t2t[j].indices[0]

        uH_v = _eval_p1_2d(CH[:, KH, :], xy)  # (2, 3)
        uh_v = _eval_p1_2d(Ch[:, kh, :], xy)  # (2, 3)

        diff_v = uH_v - uh_v

        M = area * M_ref

        for comp in range(2):
            numerator_sq += float(diff_v[comp] @ M @ diff_v[comp])
            denominator_sq += float(uh_v[comp] @ M @ uh_v[comp])

    return numerator_sq, denominator_sq

def _p1_coefficients_from_nodal_values_1d(
    sd: pp.Grid,
    nodal_values: np.ndarray,
    node_s: np.ndarray,
) -> np.ndarray:
    """Compute cell-wise coefficients as a P1 continuous field in a 1D line.

    Parameters: 
        sd: 1D grid.
        nodal_values: vector, shape = (n_components, num_nodes).
        node_s: shape = (1, num_nodes), in the same coordinate frame used 
            by :class:`TransferGrid`.

    Returns: 
        coeff: shape = (n_components, num_cells, 2)
            For each component and cell, two coefficients [a, b] define the field. 
            coeff[comp, cell] = [a, b] represents u(s) = a*s + b.
    """
    n_comp = nodal_values.shape[0]
    cells = _cell_nodes(sd)

    coeff = np.zeros((n_comp, sd.num_cells, 2))

    for i, (n0, n1) in enumerate(cells):
        s0 = float(node_s[n0])
        s1 = float(node_s[n1])

        for j in range(n_comp):
            v0 = float(nodal_values[j, n0])
            v1 = float(nodal_values[j, n1])

            a = (v1 - v0) / (s1 - s0)
            b = v0 - a * s0

            coeff[j, i, :] = [a, b]

    return coeff


def _eval_p1_1d(coeff: np.ndarray, s: np.ndarray) -> np.ndarray:
    """Evaluate the P1 field at given points in 1D.
    
    Parameters: 
        coeff: shape = (n_components, 2)
        s: shape = (n_points,)

    Returns:
        shape = (n_components, n_points)
    """
    return coeff[:, 0:1] * s[None, :] + coeff[:, 1:2]


def fracture_error_integration_p1_quad(
    sd_H: pp.Grid,
    sd_h: pp.Grid,
    wH_cc: np.ndarray,
    wh_cc: np.ndarray,
    weight: str = "volume",
    tol: float = 1e-8,
    num_quad: int = 3,
) -> tuple[float, float]:
    """Compute overlap-based relative L2 error components for P1 fields on 
    1D fracture grids using the quadrature rule.

    This implementation accesses the line grid transfer methodology,  
    :class:`TransferLine`, developed by Jhabriel Varela. 
    
    Reference: 
        - Varela, et al. (2025). arXiv preprint arXiv:2512.09087.
    
    Using num_quad = 3 is enough to cover the squared error of P1 and P2 fields 
    (degrees 2 and 4, respectively).

    It computes: 
        numerator_sq   = ∫_Gamma |w_H^P1 - w_h^P1|^2 ds
        denominator_sq = ∫_Gamma |w_h^P1|^2 ds
    """
    tl = TransferLine(sd_H, sd_h, tol=tol, name="fracture_transfer")

    # Reconstruct nodal values from cell-center values on the original grids.
    wH_node = _nodal_average_from_cell_values(sd_H, wH_cc, weight=weight)
    wh_node = _nodal_average_from_cell_values(sd_h, wh_cc, weight=weight)

    # Get rotated grids from source (coarse) and target (fine) grids.
    sH = tl._x_in_common_frame(sd_H, use_rotation=tl._rotate_source)
    sh = tl._x_in_common_frame(sd_h, use_rotation=tl._rotate_target)

    # Compute P1 coefficients for coarse and fine grids in the shared rotated coordinates.
    CH = _p1_coefficients_from_nodal_values_1d(sd_H, wH_node, sH)
    Ch = _p1_coefficients_from_nodal_values_1d(sd_h, wh_node, sh)

    xtr = tl.transfer.nodes[0, :]
    # Get the mapping from transfer cells to source (coarse) and 
    # target (fine) grids.
    t2s = tl.transfer_to_source.tocsr()
    t2t = tl.transfer_to_target.tocsr()

    numerator_sq = 0.0
    denominator_sq = 0.0
    for j in range(tl.transfer.num_cells):
        s0 = float(xtr[j])
        s1 = float(xtr[j + 1])

        # Get the parent coarse and fine cells corresponding to 
        # the current transfer cell.
        KH = t2s[j].indices[0]
        kh = t2t[j].indices[0]

        quad_s, quad_w = QuadratureIntegration.segment_quadrature_gauss(
            s0, s1, num_quad=num_quad
        )

        wH_q = _eval_p1_1d(CH[:, KH, :], quad_s)
        wh_q = _eval_p1_1d(Ch[:, kh, :], quad_s)

        diff_q = wH_q - wh_q

        numerator_sq += float(np.sum(quad_w * np.sum(diff_q**2, axis=0)))
        denominator_sq += float(np.sum(quad_w * np.sum(wh_q**2, axis=0)))

    return numerator_sq, denominator_sq

def fracture_error_integration_p1_exact(
    sd_H: pp.Grid,
    sd_h: pp.Grid,
    wH_cc: np.ndarray,
    wh_cc: np.ndarray,
    weight: str = "volume",
    tol: float = 1e-8,
) -> tuple[float, float]:
    """Compute overlap-based relative L2 error components for P1 fields on 
    1D fracture grids using the exact integration.

    Notes:
        This is a reference implementation for testing the quadrature-based method. 
        The exact integration is performed by the exact 1D P1 mass matrix on each 
        triangle. This cannot be used for P2 fields. 
    """
    # if sd_H.dim != 1 or sd_h.dim != 1:
    #     raise ValueError("fracture_overlap_l2_components_p1 expects 1D grids.")

    tl = TransferLine(sd_H, sd_h, tol=tol, name="fracture_transfer")

    wH_node = _nodal_average_from_cell_values(sd_H, wH_cc, weight=weight)
    wh_node = _nodal_average_from_cell_values(sd_h, wh_cc, weight=weight)

    sH = tl._x_in_common_frame(sd_H, use_rotation=tl._rotate_source)
    sh = tl._x_in_common_frame(sd_h, use_rotation=tl._rotate_target)

    CH = _p1_coefficients_from_nodal_values_1d(sd_H, wH_node, sH)
    Ch = _p1_coefficients_from_nodal_values_1d(sd_h, wh_node, sh)

    xtr = tl.transfer.nodes[0, :]
    t2s = tl.transfer_to_source.tocsr()
    t2t = tl.transfer_to_target.tocsr()

    # Exact 1D P1 mass matrix on segment [s0, s1]:
    # ∫ phi_i phi_j ds = L/6 * [[2,1],[1,2]]
    M_ref = np.array([[2.0, 1.0], [1.0, 2.0]]) / 6.0

    numerator_sq = 0.0
    denominator_sq = 0.0

    for j in range(tl.transfer.num_cells):
        s0 = float(xtr[j])
        s1 = float(xtr[j + 1])
        length = abs(s1 - s0)

        # Get the parent coarse and fine cells corresponding to 
        # the current transfer cell.
        KH = t2s[j].indices[0]
        kh = t2t[j].indices[0]

        s_pair = np.array([s0, s1])

        wH_v = _eval_p1_1d(CH[:, KH, :], s_pair)  # (n_comp, 2)
        wh_v = _eval_p1_1d(Ch[:, kh, :], s_pair)  # (n_comp, 2)

        diff_v = wH_v - wh_v

        M = length * M_ref

        for comp in range(diff_v.shape[0]):
            numerator_sq += float(diff_v[comp] @ M @ diff_v[comp])
            denominator_sq += float(wh_v[comp] @ M @ wh_v[comp])

    return numerator_sq, denominator_sq


def interface_error_integration_p1_quad(
    sd_H: pp.Grid,
    sd_h: pp.Grid,
    mH_cc: np.ndarray,
    mh_cc: np.ndarray,
    weight: str = "volume",
    tol: float = 1e-8,
    num_quad: int = 3,
) -> tuple[float, float]:
    """Compute overlap-based relative L2 error components for P1 fields on 1D 
    interface grids using the quadrature rule.
    
    Using num_quad = 3 is enough to cover the squared error of P1 and P2 fields 
    (degrees 2 and 4, respectively).

    Parameters: 
        sd_H, sd_h: 1D fracture grids, used as geometry for each mortar side.
        mH_cc, mh_cc: Interface displacement on mortar cells.
            shape = (nd, 2 * num_fracture_cells)

        The two mortar sides are assumed ordered as:
            first num_fracture_cells cells  -> side 0
            second num_fracture_cells cells -> side 1

    Computes:
        sum_side ∫_Gamma ||u_H^side - u_h^side||^2 ds
    """
    # Two-side mortar grids can be split with the correct ordering. 
    H_side_0 = mH_cc[:, :sd_H.num_cells]
    H_side_1 = mH_cc[:, sd_H.num_cells:]

    h_side_0 = mh_cc[:, :sd_h.num_cells]
    h_side_1 = mh_cc[:, sd_h.num_cells:]

    num0, den0 = fracture_error_integration_p1_quad(
        sd_H=sd_H,
        sd_h=sd_h,
        wH_cc=H_side_0,
        wh_cc=h_side_0,
        weight=weight,
        tol=tol,
        num_quad=num_quad,
    )

    num1, den1 = fracture_error_integration_p1_quad(
        sd_H=sd_H,
        sd_h=sd_h,
        wH_cc=H_side_1,
        wh_cc=h_side_1,
        weight=weight,
        tol=tol,
        num_quad=num_quad,
    )

    return num0 + num1, den0 + den1


