"""
The convergence analysis by L2-norm error for the 2D Westergaard opening-mode benchmark
solved by quadratic FEM with quarter-point elements, with high-degree quadrature rules.

"""
from __future__ import annotations

import math
import os

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import porepy as pp
from matplotlib.ticker import LogFormatterMathtext, LogLocator, ScalarFormatter

from fems import FemWestergaardOpenMode2d
from global_conv import relative_ref_error_p2_fem_qpe
from fems.westergaard_open_fem import FemExactDirichletBCWestergaardOpen


save_fig = "figures/global_conv/qfem_qpe"
os.makedirs(save_fig, exist_ok=True)

save_csv = "data/global_conv/qfem_qpe/wo"
os.makedirs(save_csv, exist_ok=True)


def make_model_params(h: float) -> dict:
    """Create parameters for the FEM benchmark model."""
    a = 0.30
    poi = 0.25
    shear_modulus = 1.0
    lam = 2.0 * shear_modulus * poi / (1.0 - 2.0 * poi)

    return {
        "prepare_simulation": True,
        "material_constants": {
            "solid": pp.SolidConstants(
                shear_modulus=shear_modulus,
                lame_lambda=lam,
            )
        },
        "a": a,
        "domain_size": 1.0,
        "p0": 0.0,
        "sigma_inf": 1e-4,    # far_field normal stress
        "poi": poi,
        "meshing_arguments": {"cell_size": h},
        "grid_type": "simplex",
        "theta_rad": math.radians(90.0 - 0),
        "num_bem_segments": 1000,
        "error_exclusion_zone_fracture_tips": 0.0,
    }


def run_fem_benchmark_model(
    h: float,
    use_qpe: bool,
) -> object:
    """Build and solve a FEM benchmark model."""
    params = make_model_params(h=h)
    model = FemWestergaardOpenMode2d(params, use_qpe=use_qpe)
    model.model_setup_and_sol()
    return model


class WestergaardOpenReferenceSolution(FemExactDirichletBCWestergaardOpen):
    """Reference solutions for the 2D Westergaard opening-mode benchmark problem.
    """
    def displacement_from_bem(self, points_xy: np.ndarray) -> np.ndarray:
        """The reference solution generated by the boundary element method.
        """
        segment_length = 2.0 * self.a / self.n

        center = np.array([
            0.5 * self.length,
            0.5 * self.length,
            0.0,
        ])
        bem_centers = self.get_bem_centers(segment_length, center)

        eta = np.linalg.norm(
            bem_centers[:2, :] - center[:2, None], axis=0,
        )

        u_open = -self.analytical_displacements(eta)

        dx = points_xy[0][None, :] - bem_centers[0, :, None]
        dy = points_xy[1][None, :] - bem_centers[1, :, None]

        alpha = np.pi / 2.0 - self.theta_rad

        x_bar = np.cos(alpha) * dx + np.sin(alpha) * dy
        y_bar = -np.sin(alpha) * dx + np.cos(alpha) * dy

        # Displacement contributed by each BEM segment to the points in the domain.
        u_ref_x, u_ref_y = self.bem_kernel_displacement(
            (x_bar, y_bar), segment_length / 2.0, u_open[:, None],
        )
        u_frac = np.vstack((
            np.sum(u_ref_x, axis=0),
            np.sum(u_ref_y, axis=0),
        ))

        # Note: refer to the implementation in displacement_at_point().
        t = np.array([np.sin(self.theta_rad), np.cos(self.theta_rad)])
        n = np.array([-np.cos(self.theta_rad), np.sin(self.theta_rad)])

        r_xy = points_xy - center[:2, None]
        r_t = t @ r_xy   # Local tangential coordinate
        r_n = n @ r_xy   # Local normal coordinate

        eps_coeff = self.sigma_inf / (2.0 * self.mu + 2.0 * self.lam)
        u_inf = eps_coeff * (
            t[:, None] * r_t[None, :] + n[:, None] * r_n[None, :]
        )

        return u_frac + u_inf

    def displacement_jump_from_analytical(self, point_s: np.ndarray) -> np.ndarray:
        """The reference solution generated by the analytical solution of
        displacement jumps.
        """
        displacement_jump = self.analytical_displacements(np.abs(point_s))

        # This return should be consistent with the return of displacement jump in QFEM-QPE model.
        # The first row is the tangential displacement jump, and the second row is the normal
        # displacement jump.
        return np.vstack(
            (np.zeros_like(displacement_jump), displacement_jump)
        )


if __name__ == "__main__":
    cell_sizes = [0.1, 0.05, 0.025, 0.0124, 0.00625]

    use_qpe = True

    reference = WestergaardOpenReferenceSolution(
        make_model_params(cell_sizes[0])
    )

    domain_size = reference.length
    theta_rad = reference.theta_rad

    fracture_center = np.array([0.5 * domain_size, 0.5 * domain_size])
    tangent = np.array([np.sin(theta_rad), np.cos(theta_rad)])

    results = []
    matrix_errors = []
    fracture_errors = []
    sqrt_dofs = []

    for h in cell_sizes:
        print(f"\nRunning FEM model h = {h}")
        model = run_fem_benchmark_model(
            h=h,
            use_qpe=use_qpe,
        )

        err_matrix, err_fracture = relative_ref_error_p2_fem_qpe(
            model = model,
            reference_solution_2d = reference.displacement_from_bem,
            reference_solution_1d = reference.displacement_jump_from_analytical,
            fracture_center = fracture_center,
            tangent = tangent,
            use_qpe = use_qpe,
            num_quad_matrix = 7,
            num_quad_fracture = 7,
        )

        # FEM displacement DOFs: ux and uy for every T6 node.
        matrix_dof = int(2 * model.nodes_p6.shape[0])
        sqrt_dof = float(np.sqrt(matrix_dof))

        matrix_errors.append(err_matrix)
        fracture_errors.append(err_fracture)
        sqrt_dofs.append(sqrt_dof)

        print(f"Matrix relative L2 error: {err_matrix:.6e}")
        print(f"Fracture relative L2 error: {err_fracture:.6e}")
        print(f"Matrix DOF: {matrix_dof}")

        results.append(
            {
                "h": h,
                "matrix_dof": matrix_dof,
                "matrix_error_quad": err_matrix,
                "fracture_error_quad": err_fracture,
            }
        )

    matrix_errors = np.asarray(matrix_errors)
    fracture_errors = np.asarray(fracture_errors)
    sqrt_dofs = np.asarray(sqrt_dofs)

    df = pd.DataFrame(results)
    csv_path = os.path.join(save_csv, "globalconv_qfem_qpe_wo.csv")
    df.to_csv(csv_path, index=False)
    print(f"Saved results to {csv_path}")

    # Reference lines. Adjust initial_value_line if needed for your figure.
    num_dofs_line = np.array([10, 30, 50, 70, 100, 300, 500, 1000, 3000])
    initial_value_line = 1.0e-2
    first_order_line = initial_value_line * (num_dofs_line[0] / num_dofs_line)
    second_order_line = initial_value_line * (num_dofs_line[0] / num_dofs_line) ** 2.0

    mpl.rcParams.update(
        {
            "font.family": "serif",
            "font.size": 8,
            "axes.labelsize": 8,
            "axes.titlesize": 8,
            "legend.fontsize": 7,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "lines.linewidth": 1.0,
            "lines.markersize": 2.0,
            "mathtext.fontset": "dejavusans",
        }
    )

    formatter = ScalarFormatter(useMathText=True)
    formatter.set_powerlimits((0, 0))

    fig, ax = plt.subplots(figsize=(3.5, 3.0))

    ax.loglog(
        sqrt_dofs,
        matrix_errors,
        "o-",
        color="tab:blue",
        label="QFEM-QPE matrix",
    )

    ax.loglog(
        sqrt_dofs,
        fracture_errors,
        "s-",
        color="tab:orange",
        label="QFEM-QPE fracture",
    )

    # Reference slopes.
    ax.loglog(
        num_dofs_line,
        first_order_line,
        "--",
        color="black",
        label="1st order",
    )
    ax.loglog(
        num_dofs_line,
        second_order_line,
        "--",
        color="gray",
        label="2nd order",
    )

    ax.set_xlabel(r"$\sqrt{\mathrm{DOF}}$")
    ax.set_ylabel("Relative error")

    ax.set_xlim(10, 1000)
    ax.set_ylim(0.00001, 1.0)

    ax.yaxis.set_major_formatter(formatter)
    ax.xaxis.set_major_locator(LogLocator(base=10))
    ax.xaxis.set_major_formatter(LogFormatterMathtext())
    ax.xaxis.set_minor_locator(LogLocator(base=10, subs=np.arange(2, 10) * 0.1))
    ax.yaxis.set_major_locator(LogLocator(base=10))
    ax.yaxis.set_major_formatter(LogFormatterMathtext())
    ax.yaxis.set_minor_locator(LogLocator(base=10, subs=np.arange(2, 10) * 0.1))

    ax.grid(True, which="both", linestyle="--", alpha=0.5)
    ax.legend()

    plt.tight_layout()
    plt.savefig(
        os.path.join(save_fig, "globalconv_wo_qfem_qpe.tiff"),
        format="tiff",
        dpi=300,
        bbox_inches="tight",
        pil_kwargs={"compression": "tiff_lzw"}
    )
    plt.close(fig)

    # Slope in log-log plot: log(error) = slope * log(sqrt_dof) + intercept
    slope_matrix_quad, intercept_matrix_quad = np.polyfit(
        np.log10(sqrt_dofs),
        np.log10(matrix_errors),
        1,
    )

    slope_fracture_quad, intercept_fracture_quad = np.polyfit(
        np.log10(sqrt_dofs),
        np.log10(fracture_errors),
        1,
    )

    print(f"Slope for QFEM-QPE matrix (quad): {slope_matrix_quad:.2f}")
    print(f"Slope for QFEM-QPE fracture (quad): {slope_fracture_quad:.2f}")

# Slope for QFEM-QPE matrix (quad): -1.47
# Slope for QFEM-QPE fracture (quad): -1.33


