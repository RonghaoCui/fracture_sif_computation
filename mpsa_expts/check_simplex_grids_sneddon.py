os.makedirs(save_dir, exist_ok=True)

class CheckSimplexGrids(ManuSneddonModel2d):

    def _check_triangles_angles(self, sd: pp.Grid) -> tuple[bool, int]:
        """
        Check whether all triangles in the given grid are less than 
        the threshold angle, and also return the number of triangles 
        larger than the threshold angle if any. 

        This method is adapted from :meth: `check_triangles_angles` 
        in ``GridsPerturbationMixin``.

        Parameters:
            sd: the subdomain to check. 

        Returns:
            tuple[bool, int]: 
                bool: True if all triangles are less than the threshold 
                    angle, False otherwise.
                int: The number of triangles larger than the threshold 
                    angle in the grid.

        Raises: 
            ValueError: If any cell in the grid is not a triangle 
                i.e., does not have exactly 3 nodes.

        """
        nodes = sd.nodes[:2]
        cell_to_node_mat = sd.cell_nodes()
        threshold_angle = np.pi * 0.45
        
        num_abnormal = 0

        for i in range(sd.num_cells):
            node_indices_in_cell = cell_to_node_mat[:, i].indices

            if len(node_indices_in_cell) != 3:
                raise ValueError(f"Cell {i} is not a triangle.")

            A = nodes[:, node_indices_in_cell[0]]
            B = nodes[:, node_indices_in_cell[1]]
            C = nodes[:, node_indices_in_cell[2]]

            AB = B - A
            AC = C - A
            BA = A - B
            BC = C - B
            CA = A - C
            CB = B - C 

            condA = self._calculate_angle(AB, AC) < threshold_angle
            condB = self._calculate_angle(BA, BC) < threshold_angle
            condC = self._calculate_angle(CA, CB) < threshold_angle

            if not (condA and condB and condC):
                num_abnormal += 1
        
        return num_abnormal == 0, num_abnormal
    
    def _calculate_angle(self, u, v):

        cos_theta = np.dot(u, v) / (np.linalg.norm(u) * np.linalg.norm(v))
        cos_theta = np.clip(cos_theta, -1.0, 1.0)
        
        return np.arccos(cos_theta)

a = 0.3
poi = 0.25
shear_modulus = 1.0
lam = 2 * shear_modulus * poi / (1 - 2 * poi)

params = {
    "prepare_simulation": True,
    "material_constants": {"solid": pp.SolidConstants(shear_modulus=shear_modulus, lame_lambda=lam)},
    "a": a,
    "domain_size": 1.0,
    "p0": 1e-4,
    "poi": poi,
    "meshing_arguments": {"cell_size": 0.1},
    "grid_type": "simplex",
    "theta_rad": math.radians(90 - 45),
    "num_bem_segments": 1000,
    "error_exclusion_zone_fracture_tips": 0.1,
}

#  Define mesh sizes to test 
cell_sizes = [0.1, 0.05, 0.025, 0.0125, 0.00625, 0.003125]
# cell_sizes = [0.1, 0.05, 0.025]

# Check the default simplex grids generated by gmsh without perturbation。 
num_abnormal_set = []
num_cells_set = []
for i, h in enumerate(cell_sizes):
    print(f"Running for mesh size h = {h}")
    params["meshing_arguments"] = {"cell_size": h}
    model = CheckSimplexGrids(params=params)
    pp.run_time_dependent_model(model)

    sd = model.mdg.subdomains(dim=model.nd)[0]
    is_normal, num_abnormal = model._check_triangles_angles(sd)
    
    print("Are all triangles normal in matrix? ", is_normal)
    print("Number of abnormal triangles in matrix: ", num_abnormal)

    num_cells = 0
    for g in model.mdg.subdomains(dim=2):
        num_cells += g.num_cells

    print("The number of matrix cells:", num_cells)
    
    num_abnormal_set.append(num_abnormal)
    num_cells_set.append(num_cells)

# Check the default simplex grid by gmsh and then perturb the grid with different seeds. 
# The numbers of obtuse triangles are collected and plotted.
class CheckPerturbedGrids(
    GridsPerturbationMixin, 
    ManuSneddonModel2d
):
    def __init__(self, params=None):
        super().__init__(params=params)

# Parameters for grid perturbation
params.update({
    "perturb_amplitude": 0.10,
    "perturb_exponent": 1.0,
    "perturb_seed": 1234,
})

seeds = [
    1234, 2029, 31415, 27182, 42424, 
    1414, 3201, 16180, 17333, 22002,
]

num_abnormal_pert = {seed: [] for seed in seeds}
num_cells_pert = {seed: [] for seed in seeds}

for h in cell_sizes:
    print(f"Running for mesh size h = {h}")
    params["meshing_arguments"] = {"cell_size": h}
    
    for seed in seeds:
        print(f"\nRunning seed = {seed}")
        params["perturb_seed"] = int(seed)
    
        model = CheckPerturbedGrids(params=params)
        pp.run_time_dependent_model(model)

        sd = model.mdg.subdomains(dim=model.nd)[0]
        is_normal, num_abnormal = model.check_triangles_angles(sd)

        print("Are all triangles normal in matrix? ", is_normal)
        print("Number of abnormal triangles in matrix: ", num_abnormal)

        num_cells = 0
        for g in model.mdg.subdomains(dim=2):
            num_cells += g.num_cells

        print("The number of matrix cells:", num_cells)
        
        num_abnormal_pert[seed].append(num_abnormal)
        num_cells_pert[seed].append(num_cells)

# Set the plot format
mpl.rcParams.update({
    "font.family": "serif",     
    "font.size": 8,             
    "axes.labelsize": 8,       
    "axes.titlesize": 8,        
    "legend.fontsize": 7,
    "xtick.labelsize": 8,
    "ytick.labelsize": 8,
    "lines.linewidth": 1.5,      
    "lines.markersize": 3.0,       
    "mathtext.fontset": "dejavusans",  
})

# Plot
num_abnormal_set = np.array(num_abnormal_set)
num_cells_set = np.array(num_cells_set)

fig1, ax1 = plt.subplots(figsize=(4.5, 3.0))   # inches
ax1.plot(
    num_cells_set,
    num_abnormal_set,
    'o-',
    color='tab:blue',
    label="Gmsh by default"
)

for i, seed in enumerate(seeds):
    num_obtuse = np.array(num_abnormal_pert[seed])
    num_cells = np.array(num_cells_pert[seed])
    ax1.plot(
        num_cells,
        num_obtuse,
        'o--',
        alpha=0.7,
        label=f"Perturbed, seed{i+1}"
    )

ax1.set_xscale("log")
ax1.set_xlabel("Number of cells")
ax1.set_ylabel("The number of bad triangles")

# ax1.set_xlim(10, 700)
# ax1.set_ylim(0.0002, 1.0)
ax1.xaxis.set_major_locator(LogLocator(base=10))
ax1.xaxis.set_major_formatter(LogFormatterMathtext())
ax1.xaxis.set_minor_locator(LogLocator(base=10, subs=np.arange(2, 10) * 0.1))

ax1.grid(True, which="both", linestyle="--", alpha=0.5)
# ax1.legend(loc="upper left")
ax1.legend(
    loc="center left",
    bbox_to_anchor=(1.02, 0.5),  
    frameon=False,
    fontsize=8.0,
)
plt.tight_layout()
plt.savefig(
    os.path.join(save_dir, "check_simplex_grids_pert.tiff"),
    format="tiff",
    dpi=300,
    bbox_inches="tight",
    pil_kwargs={"compression": "tiff_lzw"}
)
plt.close(fig1)


