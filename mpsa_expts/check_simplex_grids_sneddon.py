"""
Check the quality of default simplex grids generated by gmsh for 
the 2D domain with the single central fracture. 

We take the Sneddon problem as an example and generate simplex grids 
with different mesh sizes. 

The numbers of obtuse triangles in the matrix domain for different 
mesh sizes are plotted.

"""

from __future__ import annotations

import porepy as pp
import numpy as np

from gmshrandom.grids_perturbation import GridsPerturbationMixin
from tests.functional.setups.manu_sneddon_2d import ManuSneddonModel2d

import math
